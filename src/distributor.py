import json
import logging
import os
from datetime import datetime, timezone
from typing import List
import requests
from src.config import Config
from src.normalizer import NormalizedIoC

logger = logging.getLogger(__name__)

class CTIDistributor:
    def __init__(self):
        os.makedirs(Config.OUTPUT_DIR, exist_ok=True)
        self.webhook_url = Config.SLACK_WEBHOOK_URL

    def export_json_feed(self, iocs: List[NormalizedIoC]) -> str:
        filepath = os.path.join(Config.OUTPUT_DIR, "normalized_iocs.json")
        payload = {
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "total_count": len(iocs),
            "indicators": [ioc.model_dump() for ioc in iocs],
        }
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)
        logger.info(f"Exported normalized JSON feed to {filepath}")
        return filepath

    def update_firewall_rules(self, iocs: List[NormalizedIoC]) -> str:
        ip_iocs = [ioc for ioc in iocs if ioc.ioc_type == "ip"]
        blocklist_path = os.path.join(Config.OUTPUT_DIR, "firewall_blocklist.txt")
        iptables_script = os.path.join(Config.OUTPUT_DIR, "apply_iptables.sh")

        with open(blocklist_path, "w", encoding="utf-8") as bf, open(
            iptables_script, "w", encoding="utf-8"
        ) as sf:
            sf.write("#!/bin/sh\n")
            sf.write("# Auto-generated by Automated Threat Intelligence Orchestrator\n")
            sf.write("iptables -N CTI_BLOCKLIST 2>/dev/null || iptables -F CTI_BLOCKLIST\n")

            for ioc in ip_iocs:
                bf.write(f"{ioc.value}\n")
                sf.write(
                    f"iptables -A CTI_BLOCKLIST -s {ioc.value} -j DROP "
                    f"-m comment --comment \"CTI:{ioc.severity}:{ioc.source_pulse[:25]}\"\n"
                )

        os.chmod(iptables_script, 0o750)
        logger.info(
            f"Generated firewall rules for {len(ip_iocs)} malicious IPs at {iptables_script}"
        )
        return iptables_script

    def send_slack_alert(self, iocs: List[NormalizedIoC]) -> bool:
        high_confidence = [ioc for ioc in iocs if ioc.severity == "HIGH"]
        if not high_confidence:
            logger.info("No HIGH severity IoCs found. Skipping Slack alert.")
            return False

        summary_lines = [
            f"• `{ioc.value}` ({ioc.ioc_type.upper()}) — Score: *{ioc.confidence_score}/100* | Pulse: _{ioc.source_pulse}_"
            for ioc in high_confidence[:10]
        ]

        slack_payload = {
            "text": f"🚨 *High-Confidence Threat Intelligence Alert* ({len(high_confidence)} new indicators)",
            "blocks": [
                {
                    "type": "header",
                    "text": {
                        "type": "plain_text",
                        "text": "🚨 High-Confidence CTI Alert Detected",
                    },
                },
                {
                    "type": "section",
                    "text": {
                        "type": "mrkdwn",
                        "text": (
                            f"Ingested *{len(high_confidence)} HIGH-severity* Indicators of Compromise. "
                            f"Firewall blocklists have been automatically updated.\n\n"
                            + "\n".join(summary_lines)
                        ),
                    },
                },
            ],
        }

        if not self.webhook_url or "T0000" in self.webhook_url:
            logger.info(
                f"[Dry-Run] Slack Webhook not configured. Would have alerted on {len(high_confidence)} HIGH-severity IoCs."
            )
            return False

        try:
            resp = requests.post(self.webhook_url, json=slack_payload, timeout=10)
            resp.raise_for_status()
            logger.info("Dispatched high-confidence alert to Slack webhook.")
            return True
        except requests.RequestException as exc:
            logger.error(f"Failed to send Slack webhook alert: {exc}")
            return False